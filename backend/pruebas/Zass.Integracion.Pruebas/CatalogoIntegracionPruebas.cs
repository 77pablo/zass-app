    /// <summary>
    /// Y el camino completo: escribir a mano un servicio que ya esta en el catalogo no
    /// crea una segunda fila, reutiliza la que hay.
    /// </summary>
    [Fact]
    public async Task Escribir_un_nombre_que_ya_existe_reutiliza_el_servicio_del_catalogo()
    {
        var perfil = await UnPrestadorAsync();
        var delCatalogo = await _prueba.Ctx.Servicios.FirstAsync(s => s.Id == 101);
        var cuantos = await _prueba.Ctx.Servicios.CountAsync();

        var r = await _servicio.ReemplazarServiciosAsync(Cmd(perfil.Id,
            new ServicioOfrecidoCmd(null, delCatalogo.Nombre.ToUpperInvariant(), 60, "manual", null)));

        Assert.True(r.Exito, r.Mensaje);
        Assert.Equal(cuantos, await _prueba.Ctx.Servicios.CountAsync());
        var oferta = await _prueba.Ctx.PrestadorServicios
            .SingleAsync(o => o.PerfilPrestadorId == perfil.Id);
        Assert.Equal(101, oferta.ServicioId);
    }

