    private async Task<PerfilPrestador> UnPrestadorAsync()
    {
        var usuario = new Usuario
        {
            Correo = $"cat-{Guid.NewGuid():N}@zass.local",
            HashContrasena = "x",
            Nombre = "Prestador de prueba",
            CorreoVerificado = true,
        };
        _prueba.Ctx.Usuarios.Add(usuario);

        var perfil = new PerfilPrestador
        {
            UsuarioId = usuario.Id,
            NombrePublico = $"Estudio {Guid.NewGuid():N}",
            Slug = $"estudio-{Guid.NewGuid():N}",
            RubroId = Corretaje,
        };
        _prueba.Ctx.PerfilesPrestador.Add(perfil);
        await _prueba.Ctx.SaveChangesAsync();
        return perfil;
    }

    private static ReemplazarServiciosCmd Cmd(Guid perfilId, params ServicioOfrecidoCmd[] s) =>
        new(perfilId, Corretaje, MaxServicios: 10, s);

    private static ServicioOfrecidoCmd DelCatalogo(int id, short duracion = 60) =>
        new(id, null, duracion, "automatico", null);

