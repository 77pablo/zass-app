    /// <summary>
    /// La prueba que justifica todo el diseno de ReemplazarServicios.
    ///
    /// TBL-13 `disponibilidad` y TBL-18 `cita` apuntan a `prestador_servicio` con
    /// ON DELETE CASCADE. Si reemplazar borrara y volviera a crear las filas, quitar un
    /// servicio de la lista —o incluso solo cambiarle el precio— se llevaria por delante
    /// los horarios y las citas de ese servicio, sin aviso y sin error.
    /// </summary>
    [Fact]
    public async Task Quitar_un_servicio_de_la_lista_no_borra_sus_horarios()
    {
        var perfil = await UnPrestadorAsync();
        await _servicio.ReemplazarServiciosAsync(
            Cmd(perfil.Id, DelCatalogo(101), DelCatalogo(102)));

        var oferta = await _prueba.Ctx.PrestadorServicios
            .SingleAsync(o => o.PerfilPrestadorId == perfil.Id && o.ServicioId == 102);

        _prueba.Ctx.Disponibilidades.Add(new Disponibilidad
        {
            PerfilPrestadorId = perfil.Id,
            PrestadorServicioId = oferta.Id,
            DiaSemana = 3,
            HoraInicio = new TimeOnly(9, 0),
            HoraFin = new TimeOnly(13, 0),
            VigenteDesde = new DateOnly(2026, 11, 1),
        });
        await _prueba.Ctx.SaveChangesAsync();

        // El servicio 102 sale de la lista
        var r = await _servicio.ReemplazarServiciosAsync(Cmd(perfil.Id, DelCatalogo(101)));

        Assert.True(r.Exito, r.Mensaje);
        Assert.True(await _prueba.Ctx.Disponibilidades.AnyAsync(d => d.PrestadorServicioId == oferta.Id),
            "la disponibilidad desaparecio: reemplazar borro la fila en vez de desactivarla");

        var despues = await _prueba.Ctx.PrestadorServicios
            .SingleAsync(o => o.PerfilPrestadorId == perfil.Id && o.ServicioId == 102);
        Assert.Equal(oferta.Id, despues.Id);
        Assert.False(despues.Activo);
    }

    /// <summary>
    /// Lo mismo contado al reves: el identificador de la oferta que se queda no cambia,
    /// asi que nada de lo que cuelga de ella se entera de la edicion.
    /// </summary>
    [Fact]
    public async Task Editar_la_duracion_conserva_el_identificador_de_la_oferta()
    {
        var perfil = await UnPrestadorAsync();
        await _servicio.ReemplazarServiciosAsync(Cmd(perfil.Id, DelCatalogo(101, duracion: 60)));
        var antes = await _prueba.Ctx.PrestadorServicios
            .SingleAsync(o => o.PerfilPrestadorId == perfil.Id);

        await _servicio.ReemplazarServiciosAsync(Cmd(perfil.Id, DelCatalogo(101, duracion: 90)));

        var despues = await _prueba.Ctx.PrestadorServicios
            .SingleAsync(o => o.PerfilPrestadorId == perfil.Id);
        Assert.Equal(antes.Id, despues.Id);
        Assert.Equal(90, despues.DuracionMinutos);
    }

