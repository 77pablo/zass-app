    /// <summary>
    /// ux_servicio_rubro_nombre, sobre la columna normalizada.
    ///
    /// Esta prueba encontro un fallo de verdad. Al principio el indice iba sobre
    /// lower(nombre), y no rechazaba nada: este cluster se creo con locale C, y ahi
    /// lower() solo plega ASCII, asi que lower('Ó') sigue siendo 'Ó' y
    /// "TASACIÓN COMERCIAL" entraba al lado de "Tasación comercial". La regla dependia
    /// del locale del servidor, que en Azure sera otro.
    ///
    /// Ahora la clave la calcula Texto.ClaveDeNombre en C# y la columna la guarda, asi
    /// que la igualdad es exacta y no depende de nada del servidor.
    /// </summary>
    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public async Task La_base_rechaza_el_mismo_servicio_escrito_distinto(bool enMayusculas)
    {
        var delCatalogo = await _prueba.Ctx.Servicios.FirstAsync(s => s.Id == 101);
        var comoLoEscribieron = enMayusculas
            ? delCatalogo.Nombre.ToUpperInvariant()   // TASACIÓN COMERCIAL
            : delCatalogo.Nombre;

        _prueba.Ctx.Servicios.Add(new Servicio
        {
            RubroId = delCatalogo.RubroId,
            Nombre = comoLoEscribieron,
            NombreNormalizado = Texto.ClaveDeNombre(comoLoEscribieron),
            EsCatalogo = false,
        });

        var error = await Assert.ThrowsAsync<DbUpdateException>(
            () => _prueba.Ctx.SaveChangesAsync());
        Assert.Equal("23505", (error.InnerException as PostgresException)?.SqlState);
    }

    /// <summary>
